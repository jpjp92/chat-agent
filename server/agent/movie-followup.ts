/**
 * 영화 상영표 턴 규칙 — 순수.
 *
 * 2026-09-24 에 `prompt-assembly.ts` 의 인라인 문자열에서 떼어냈다. 이유는 하나다 —
 * **하니스가 문구 자체를 검사할 수 있게** 하려는 것이다. 인라인 리터럴은 소스 grep 으로만
 * 볼 수 있었고, 소스 grep 은 문구가 이사하면 거짓으로 깨지고 문구가 바뀌어도 통과한다
 * (2026-09-24 에 실제로 11건이 그렇게 깨졌다).
 *
 * 문구는 옮기면서 **한 글자도 바꾸지 않았다.** 골든 해시가 그걸 지킨다
 * (`tests/test-prompt-assembly.mts` 의 `turn/movieSearch`).
 */

/**
 * 화면 상영표를 근거로 후속 질문에 답하게 한다.
 *
 * 🔴 검색 턴(`movieSearchTurn`)도 이 규칙을 받는다. 예전엔 `movieFollowup` 만 봐서,
 * "줄거리 검색해줘" 턴에 화면 상영작이 모델에게 전달되지 않았다 — 오디세이가 CGV 강남에
 * 걸려 있는데 "'오디세이'라는 제목의 영화는 찾기 어렵지만" 하며 **마션 줄거리**를
 * 답했다(실측 2026-08-31). 모델의 학습 시점 이후 개봉작이면 그냥 없는 영화가 된다.
 */
export const buildMovieFollowupRules = (movieContext: string): string =>
    `${movieContext}\n\n[영화 상영표 후속 질문 처리 규칙]\n- 위 "현재 화면에 표시된 영화 상영시간표" 데이터를 근거로 사용자의 후속 질문(비교·필터·"~만 상영"·가장 빠른/늦은 회차 등)에 간결히 답하세요.\n- 데이터에 없는 정보(줄거리·평점·예매율·관객수·장르·다른 지역/지점 등)는 절대 지어내지 마세요. 대신 "상영표에는 그 정보가 없어요"라고 밝힌 뒤, 반드시 마지막에 "웹에서 검색해 드릴까요?"라고 사용자에게 물어보세요. (사용자가 동의하면 다음 턴에 자동으로 웹 검색이 수행됩니다.)\n- json:movie 카드 블록을 다시 생성하지 마세요(이미 화면에 있음). 텍스트로만 답하세요.`;

/**
 * 검색 결과보다 화면이 우선이라고 못 박는다.
 *
 * 상영표는 극장사에서 방금 받아온 값이라 "그 영화가 실재하고 지금 상영 중" 이라는 사실의
 * 근거로는 웹 검색보다 강하다.
 */
export const buildMovieSearchRules = (): string =>
    `[화면 상영작에 대한 웹 검색 규칙]\n- 화면에 표시된 제목은 실재하는 상영작입니다. 극장 상영표에서 방금 조회한 값이므로, 검색 결과가 부실하더라도 "그런 영화를 찾을 수 없다"고 말하거나 **다른 영화로 바꿔 답하지 마세요**.\n- 사용자가 물은 그 제목에 대해서만 답하세요. 정보를 못 찾았으면 못 찾았다고 그대로 밝히세요(비슷한 다른 작품의 줄거리로 대체하는 것은 명백한 오답입니다).\n- 최신 개봉작이라 사전 지식에 없을 수 있습니다. 화면 상영표가 그 영화의 존재를 증명합니다.`;
