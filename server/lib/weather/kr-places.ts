// 맨 이름이 동명인 경우의 기본값 — 위 주석의 규칙
const DEFAULTS: Record<string, string> = { 고성: '경남고성' };

const PROVINCES: [RegExp, string][] = [
  [/^서울특별시/, '서울'], [/^부산광역시/, '부산'], [/^대구광역시/, '대구'], [/^인천광역시/, '인천'],
  [/^광주광역시/, '광주'], [/^대전광역시/, '대전'], [/^울산광역시/, '울산'], [/^세종특별자치시/, '세종'],
  [/^경기도/, '경기'], [/^강원(특별자치)?도/, '강원'], [/^충청북도/, '충북'], [/^충청남도/, '충남'],
  [/^전북특별자치도|^전라북도/, '전북'], [/^전라남도/, '전남'], [/^경상북도/, '경북'], [/^경상남도/, '경남'],
  [/^제주특별자치도/, '제주'],
];
const SHORT_PROVINCE = /^(경기|강원|충북|충남|전북|전남|경북|경남|제주)(?=.)/;

function lookup(key: string): KrPlace | undefined {
  const k = DEFAULTS[key] ?? key;
  const hit = TABLE[k];
  return hit ? { lat: hit.lat, lon: hit.lon, label: hit.label ?? k } : undefined;
}

const stripSuffix = (s: string) => (s.length > 2 ? s.replace(/(특별자치시|특별시|광역시|시|군)$/, '') : s);

/** 국내 시·군 이름(또는 "시·군 + 구·동")이면 좌표, 아니면 undefined(해외 등 → 호출부가 OWM 으로). */
export function findKrPlace(input: string): KrPlace | undefined {
  const whole = findWhole(input);
  if (whole) return whole;
  // "부산 해운대"·"서울 강남구" — 구·동은 표에 없다. 앞 단어가 시·군이면 그 좌표(단기 격자 5km·중기 광역 단위라 충분)
  // 앞 단어를 길게부터 — "경기 광주 오포" 는 "경기 광주" 가 먼저 잡혀야 한다("경기" 단독은 표에 없다)
  const words = input.trim().split(/\s+/);
  for (let n = words.length - 1; n >= 1; n--) {
    const hit = findWhole(words.slice(0, n).join(' '));
    if (hit) return hit;
  }
  return undefined;
}

function findWhole(input: string): KrPlace | undefined {
  let s = input.replace(/\s+/g, '').replace(/,?(대한민국|한국|KR|korea)$/i, '');
  if (!s) return undefined;
  const direct = lookup(s) ?? (s === '제주도' ? lookup('제주') : undefined);
  if (direct) return direct;
  for (const [re, short] of PROVINCES) if (re.test(s)) { s = s.replace(re, short); break; }
  s = stripSuffix(s);
  const withProvince = lookup(s);
  if (withProvince) return withProvince;
  if (SHORT_PROVINCE.test(s)) {
    // 도명 + 동명(경기 광주·강원 고성)은 위에서 잡혔다 — 남은 건 도명을 떼어도 뜻이 같다(전남 광주 → 광주)
    const bare = stripSuffix(s.replace(SHORT_PROVINCE, ''));
    if (bare) return lookup(bare);
  }
  return undefined;
}
